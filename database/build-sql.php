function q($v): string
{
    if ($v === null) return 'NULL';
    if (is_int($v) || is_float($v)) return (string) $v;
    if (is_bool($v)) return $v ? '1' : '0';
    if ($v instanceof RawSql) return $v->sql;
    return "'" . strtr((string) $v, ["\\" => "\\\\", "'" => "\\'", "\n" => "\\n", "\r" => "\\r", "\0" => "\\0"]) . "'";
}
final class RawSql { public function __construct(public string $sql) {} }
function raw(string $s): RawSql { return new RawSql($s); }
function insert(string $table, array $row): string
{
    return "INSERT INTO `$table` (`" . implode('`,`', array_keys($row)) . "`) VALUES (" . implode(',', array_map('q', array_values($row))) . ");\n";
}

